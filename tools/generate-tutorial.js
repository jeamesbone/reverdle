#!/usr/bin/env node
/**
 * Picks the worked example shown in the menu.
 *
 * Same shape and same guarantee as a daily puzzle - five letters, four rows,
 * every pattern produced by exactly one word in the whole dictionary - but
 * chosen to teach rather than to be solved. The rows are picked for variety:
 * one that is mostly green, one carrying greys, one heavy on yellows, so
 * reading them in order walks through what each colour means.
 *
 * Usage: node tools/generate-tutorial.js
 * Writes: data/tutorial.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ROWS = 4;

const read = (f) =>
  fs.readFileSync(path.join(ROOT, 'data', f), 'utf8')
    .split(/\s+/)
    .filter((w) => /^[a-z]{5}$/.test(w));

const GUESS = read('words-guess.txt');
const COMMON = read('words-common.txt');
const commonSet = new Set(COMMON);

function score(guess, answer) {
  const out = [0, 0, 0, 0, 0];
  const left = {};
  for (let i = 0; i < 5; i++) {
    if (guess[i] === answer[i]) out[i] = 2;
    else left[answer[i]] = (left[answer[i]] || 0) + 1;
  }
  for (let i = 0; i < 5; i++) {
    if (out[i] === 0 && left[guess[i]] > 0) {
      out[i] = 1;
      left[guess[i]]--;
    }
  }
  return out.join('');
}

const count = (pattern, ch) => (pattern.match(new RegExp(ch, 'g')) || []).length;

function unambiguousTargets(answer) {
  const byPattern = new Map();
  for (const w of GUESS) {
    const p = score(w, answer);
    let bucket = byPattern.get(p);
    if (!bucket) byPattern.set(p, (bucket = []));
    bucket.push(w);
  }
  const out = [];
  for (const [pattern, words] of byPattern) {
    if (pattern === '22222') continue;
    if (words.length !== 1) continue;
    if (!commonSet.has(words[0])) continue;
    out.push({ pattern, word: words[0] });
  }
  return out;
}

/** How much a set of rows teaches: distinct shapes, and every colour shown. */
function teachingValue(rows) {
  const greens = rows.map((r) => count(r.pattern, '2'));
  const distinct = new Set(greens).size;
  const opener = Math.max(...greens);
  const yellows = Math.max(...rows.map((r) => count(r.pattern, '1')));
  const greys = Math.max(...rows.map((r) => count(r.pattern, '0')));
  if (opener < 3) return -1; // the first row has to be readable at a glance
  if (yellows < 3) return -1; // and one row should really lean on yellows
  if (greys < 1) return -1; // and one should show a letter that is simply absent
  return distinct * 10 + yellows + greys;
}

let best = null;
for (const answer of COMMON) {
  const cand = unambiguousTargets(answer);
  if (cand.length < ROWS) continue;
  // Easiest first: greens pin a letter down, yellows only hint.
  cand.sort(
    (a, b) =>
      2 * count(b.pattern, '2') + count(b.pattern, '1') -
      (2 * count(a.pattern, '2') + count(a.pattern, '1'))
  );
  const step = (cand.length - 1) / (ROWS - 1);
  const rows = [];
  for (let i = 0; i < ROWS; i++) rows.push(cand[Math.round(i * step)]);

  const value = teachingValue(rows);
  if (value > 0 && (!best || value > best.value)) best = { answer, rows, value };
}

if (!best) throw new Error('no answer word makes a good enough example');

fs.writeFileSync(
  path.join(ROOT, 'data', 'tutorial.js'),
  '// Generated by tools/generate-tutorial.js - do not edit by hand.\n' +
    'const TUTORIAL = ' +
    JSON.stringify({ a: best.answer, r: best.rows.map((r) => [r.pattern, r.word]) }) +
    ';\n'
);

console.log('picked:', best.answer, JSON.stringify(best.rows), 'value', best.value);
